# Read-only oracle checkpoint; none of these are regenerated by the repair.
def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def independent_rg8(pack: dict, feature_id: str | None = None) -> bytes:
    """Independent row-stamp oracle, not adapter source or expected-hash copying."""
    assert pack["schema_id"] == SCHEMA and pack["schema_version"] == 1
    scene = pack.get("scene", pack.get("combined_scene"))
    features = {f["id"]:f for f in pack["features"]}
    if feature_id is None:
        w, h = scene["size"]
    else:
        w, h = features[feature_id]["size"]
    out = bytearray(w*h*2)
    def stamp(rect, dx=0, dy=0, swap=None):
        x,y,rw,rh,mat=rect
        mat = int((swap or {}).get(str(mat),mat))
        assert 0 <= x+dx <= w-rw and 0 <= y+dy <= h-rh
        row = bytes((mat, CONDITIONS.get(mat,0)))*rw
        for iy in range(y+dy,y+dy+rh):
            start=((iy*w)+(x+dx))*2
            out[start:start+rw*2] = row
    if feature_id is not None:
        for rect in features[feature_id]["rectangles"]:
            stamp(rect)
    else:
        for rect in scene.get("rectangles",scene.get("terrain_rectangles",[])):
            stamp(rect)
        for placement in scene["placements"]:
            if "scene" in pack:
                fid=placement["feature"]; dx=placement["x"]; dy=placement["y"]
            else:
                fid=placement["feature_id"]; dx,dy=placement["origin"]
            feature=features[fid]
            variant=placement.get("variant")
            swaps = {}
            if variant not in (None,"","base","default"):
                matches=[v for v in feature.get("variants",[]) if v["id"]==variant]
                assert len(matches)==1
                swaps=matches[0].get("swap",{})
            for rect in feature["rectangles"]:
                stamp(rect,dx,dy,swaps)
    return bytes(out)


