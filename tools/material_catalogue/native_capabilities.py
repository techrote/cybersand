#!/usr/bin/env python3
"""Generate the bounded native hard/granular capability consumer.

The schema-1 compiler remains the single validator of authored material data.
This separate #353-B route owns only two explicit capability masks; descriptors,
IDs, reaction tables, visual state and policy identities remain existing owners.
An isolated synthetic header is never published into the source tree.
"""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import tempfile

import compiler

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "materials/catalogue/catalogue.json"
OUTPUT = ROOT / "native/include/cybersand/material_capabilities.hpp"
FIELDS = ("hard_surface", "granular_support")
GENERATOR_VERSION = 1


def render(catalogue: dict) -> bytes:
    """Render a previously validated catalogue without reading native facts."""
    source_sha = hashlib.sha256(compiler.canonical_json(catalogue)).hexdigest()
    declarations = []
    for field, symbol in (("hard_surface", "kHardSurface"),
                          ("granular_support", "kGranularSupport")):
        words = [0] * 4
        for row in catalogue["native"]["capabilities"]:
            if row[field]:
                words[row["id"] >> 6] |= 1 << (row["id"] & 63)
        declarations.append(
            "inline constexpr std::array<std::uint64_t, 4> " + symbol + "{{\n    "
            + ", ".join(f"0x{word:016x}ULL" for word in words) + "\n}};\n")
    text = (
        "// Generated by tools/material_catalogue/native_capabilities.py. Do not edit.\n"
        "// Two explicit capabilities only; no phase, name, family or numeric-range inheritance.\n"
        f"// Source schema 1; generator {GENERATOR_VERSION}; scope {catalogue['scope']}.\n"
        f"// Normalized authored source SHA-256: {source_sha}\n"
        "#pragma once\n\n#include <array>\n#include <cstdint>\n\n"
        "namespace cybersand::material_capability_catalogue {\n\n"
        + "\n".join(declarations)
        + "\n[[nodiscard]] constexpr bool contains(\n"
        "    const std::array<std::uint64_t, 4>& words, std::uint8_t material) noexcept {\n"
        "    return ((words[material >> 6U] >> (material & 63U)) & 1ULL) != 0ULL;\n"
        "}\n\n"
        "[[nodiscard]] constexpr bool hard_surface(std::uint8_t material) noexcept {\n"
        "    return contains(kHardSurface, material);\n}\n\n"
        "[[nodiscard]] constexpr bool granular_support(std::uint8_t material) noexcept {\n"
        "    return contains(kGranularSupport, material);\n}\n\n"
        "}  // namespace cybersand::material_capability_catalogue\n"
    )
    return text.encode("utf-8")


def generate(source: Path = SOURCE, output: Path = OUTPUT, *,
             check: bool = False, isolated: bool = False) -> bool:
    source, output = Path(source), Path(output)
    if output.is_symlink():
        raise compiler.CatalogueError(f"{output}#/: output must not be a symbolic link")
    destination = output.resolve()
    repository_output = destination.is_relative_to(ROOT.resolve())
    if repository_output and (destination != OUTPUT.resolve() or isolated
                              or source.resolve() != SOURCE.resolve()):
        raise compiler.CatalogueError(
            f"{output}#/: only the canonical production catalogue may generate the owned native capability header; isolated output must be external")
    if destination == source.resolve():
        raise compiler.CatalogueError(f"{output}#/: output must not overwrite the authored source")
    catalogue = compiler.load_catalogue(source, isolated=isolated)
    data = render(catalogue)
    if output.exists() and not output.is_file():
        raise compiler.CatalogueError(f"{output}#/: output must be a regular file")
    if output.exists() and output.read_bytes() == data:
        return False
    if check:
        raise compiler.DriftError(f"{output}#/: native capability header is missing or stale")
    output.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix="." + output.name + ".", dir=output.parent)
    try:
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(data)
        os.replace(temporary, output)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)
    return True


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=SOURCE)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--isolated", action="store_true",
                        help="allow the existing synthetic powder132 schema only in an external output")
    args = parser.parse_args(argv)
    try:
        changed = generate(args.source, args.output, check=args.check, isolated=args.isolated)
    except (compiler.CatalogueError, OSError) as error:
        print(error)
        return 1
    print("native capability header matches canonical source" if args.check else
          "native capability header generated" if changed else "native capability header already current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
