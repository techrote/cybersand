def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def files(root: Path) -> dict[str, str]:
    return {path.relative_to(root).as_posix(): sha(path)
            for path in sorted(root.rglob("*"))
            if path.is_file() and path != root / "candidate-manifest.json"}


def archive_environment() -> dict[str, str]:
    environment = os.environ.copy()
    count = environment.get("GIT_CONFIG_COUNT", "0")
    publication.engine.require(count.isdecimal(), "Invalid inherited Git environment configuration count")
    offset = int(count)
    # git archive applies working-tree conversion, including host autocrlf.
    # Append child-only overrides; preserve preceding configuration and explicit
    # .gitattributes eol settings (for example the intended CRLF launchers).
    for key, value in (("core.autocrlf", "false"), ("core.eol", "lf")):
        environment[f"GIT_CONFIG_KEY_{offset}"] = key
        environment[f"GIT_CONFIG_VALUE_{offset}"] = value
        offset += 1
    environment["GIT_CONFIG_COUNT"] = str(offset)
    # Archive pointers without downloading excluded platform libraries. The
    # inherited packager copies and verifies only admitted, materialized LFS.
    environment["GIT_LFS_SKIP_SMUDGE"] = "1"
    return environment


def omit_regenerated_imports(root: Path) -> dict[str, str]:
    omitted = {}
    for name, expected in REGENERATED_RAPIER_IMPORTS.items():
        path = root / name
        if not path.exists():
            continue
        observed = sha(path) if path.is_file() and not path.is_symlink() else "not a regular file"
        publication.engine.require(observed == expected,
                                   f"Reviewed Rapier import settings changed: {name}; expected={expected}; observed={observed}")
        source = path.with_suffix("")
        publication.engine.require(source.is_file() and not source.is_symlink(),
                                   "Regenerated import requires its source image: " + name)
        omitted[name] = expected
    # Complete validation precedes removal, so a changed sidecar cannot leave
    # a partially filtered package that appears to have passed this admission.
    for name in omitted:
        (root / name).unlink()
    return omitted


def stage_runtime_evidence(bundle: Path, destination: Path, identity: dict) -> dict:
    provenance = publication.engine.verify_bundle(
        bundle, "windows", identity["source_commit"], validated=True)
    publication.engine.require(provenance["sha256"] == identity["native_sha256"]
                               == sha(destination / publication.engine.RUNTIMES["windows"]),
                               "Validated runtime differs from the packaged DLL")
    provenance_name = "source-built-runtime-provenance.json"
    evidence = "qualification/runtime/"
    log_names = [name + ".log" for name in ["import", *publication.engine.CASE_MARKERS]]
    inputs = {provenance_name: publication.engine.manifest_path(bundle, "windows"),
              evidence + "validation.json": bundle / "validation.json"}
    inputs.update({evidence + name: bundle / name for name in log_names})
    payload = {name: path.read_bytes() for name, path in inputs.items()}
    # Bind the exact bytes being copied to the admitted report, including all
    # required focused logs and import. Keep the verifier's real platform/source
    # checks; copying a compiler string alone cannot qualify a runtime.
    publication.engine.require(json.loads(payload[provenance_name]) == provenance,
                               "Validated runtime provenance changed before packaging")
    publication.engine.require(hashlib.sha256(payload[evidence + "validation.json"]).hexdigest()
                               == provenance["validation_sha256"], "Validated report changed before packaging")
    report = json.loads(payload[evidence + "validation.json"])
    for name in log_names:
        publication.engine.require(hashlib.sha256(payload[evidence + name]).hexdigest()
                                   == report["log_sha256"][name], "Validated log changed before packaging: " + name)
    for name in payload:
        publication.engine.require(not (destination / name).exists(), "Runtime evidence destination already exists: " + name)
    for name, data in payload.items():
        target = destination / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    return {"provenance": provenance_name, "validation": evidence + "validation.json",
            "logs": [evidence + name for name in log_names]}


def build(args) -> None:
    command = [sys.executable, str(ROOT / "tools/package_explore001_candidate.py"),
               "--engine", str(args.engine), "--engine-notices", str(args.engine_notices),
               "--native-candidate", str(args.native_candidate),
               "--vc-runtime", str(args.vc_runtime), "--output", str(args.output),
               "--readme", "docs/operations/wave-flow-evaluation.md"]
    subprocess.run(command, cwd=ROOT, check=True, timeout=600, env=archive_environment())
    path = args.output / "candidate-manifest.json"
    manifest = json.loads(path.read_text(encoding="utf-8"))
    publication.engine.require(manifest.get("files_sha256") == files(args.output),
                               "Desktop package changed before Wave adaptation")
    qualification = stage_runtime_evidence(args.native_candidate, args.output, manifest)
    omitted = omit_regenerated_imports(args.output)
    console = args.engine.with_name(args.engine.stem + "_console.exe").name
    launcher = (
        '@echo off\ncd /d "%~dp0"\n'
        f'set "CYBERSAND_SOURCE_REVISION={manifest["source_commit"]}"\n'
        f'"%~dp0{console}" --headless --path "%~dp0godot" --editor --quit\n'
        'if errorlevel 1 (\n'
        '  if not "%~1"=="--headless" pause\n'
        '  exit /b 1\n)\n'
        f'"%~dp0{console}" --path "%~dp0godot" %* -- --workbench\n'
        'set "wave_exit=%errorlevel%"\n'
        'if not "%wave_exit%"=="0" if not "%~1"=="--headless" pause\n'
        'exit /b %wave_exit%\n'
    )
    (args.output / "Open Workbench.cmd").write_text(launcher, encoding="utf-8", newline="\r\n")
    manifest.update(purpose="Experimental Wave Flow in Shared Workbench; merge requires owner approval",
                    launcher="Open Workbench.cmd", regenerated_imports_sha256=omitted,
                    runtime_qualification=qualification,
                    files_sha256=files(args.output))
    path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(path)


def verify(package: Path) -> dict:
    path = package / "candidate-manifest.json"
    manifest = json.loads(path.read_text(encoding="utf-8"))
    publication.engine.require(manifest.get("launcher") == "Open Workbench.cmd",
                               "Wrong evaluation launcher")
    publication.engine.require(manifest.get("files_sha256") == files(package),
                               "Extracted evaluation payload differs from its SHA-256 manifest")
    publication.engine.require(sha(package / publication.engine.RUNTIMES["windows"])
                               == manifest.get("native_sha256"), "Evaluation native runtime changed")
    return manifest


def verify_original_payload(package: Path, manifest: dict, manifest_sha256: str) -> None:
    publication.engine.require(sha(package / "candidate-manifest.json") == manifest_sha256,
                               "Package manifest changed during qualification")
    # Import creates new .godot caches, generated import sidecars and UID files.
    # Recheck every original payload byte, including all authored .uid files and
    # any import settings outside the four reviewed build-time omissions.
    for name, digest in manifest["files_sha256"].items():
        publication.engine.require((package / name).is_file() and sha(package / name) == digest,
                                   "Packaged input changed during execution: " + name)


def qualify(args) -> None:
    publication.engine.require(sys.platform == "win32", "Windows package must execute on Windows")
    package, output = args.package.resolve(), args.output.resolve()
    manifest = verify(package)
    expected = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    publication.engine.require(manifest.get("source_commit") == expected,
                               "Evaluation source differs from qualification checkout")
    output.mkdir(parents=True, exist_ok=False)
    godot = package / "Godot_v4.7-stable_win64_console.exe"
    runner = publication.engine.runner
    runner.ROOT = package
    ordinary_command = runner.case_command

    def package_command(binary, case, platform=sys.platform):
        if case.name == "launcher":
            # The shared runner retains process-tree cleanup, telemetry and the
            # full watchdog. Its cwd is the extracted package, so CMD exercises
            # the delivered launcher including its own import and error path.
            return ["cmd.exe", "/d", "/c", "call", "Open Workbench.cmd",
                    "--headless", "--quit-after", "120"]
        return ordinary_command(binary, case, platform)

    runner.case_command = package_command
    policy = runner.execution_policy
    cases = [
        runner.Case("import", ("--editor", "--quit"), policy.watchdog_seconds("godot_import_seconds"), 3),
        runner.Case("test_wave_flow", ("--script", "res://tests/test_wave_flow.gd"),
                    policy.watchdog_seconds("complex_fixture_seconds"), 60),
        runner.Case("test_workbench_canvas", ("--script", "res://tests/test_workbench_canvas.gd"),
                    policy.watchdog_seconds("complex_fixture_seconds"), 60),
        runner.Case("test_workbench_wave", ("--script", "res://tests/test_workbench_wave.gd"),
                    policy.watchdog_seconds("complex_fixture_seconds"), 60),
        runner.Case("launcher", (),
                    policy.watchdog_seconds("ordinary_case_seconds"), 10),
    ]
    report = {"schema": "wave-flow-windows-package-execution-v1", "source_commit": expected,
              "native_sha256": manifest["native_sha256"], "manifest_sha256": sha(package / "candidate-manifest.json"),
              "status": "running", "cases": []}
    for case in cases:
        result, failed = runner.run_case(str(godot), case, output,
                                         "preflight" if case.name == "import" else "case")
        report["cases"].append(result)
        (output / "qualification.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        publication.engine.require(not failed and result.get("skip_messages") == [],
                                   "Extracted evaluation execution failed: " + case.name)
        if case.name == "test_wave_flow":
            publication.verify_wave_summary((output / "test_wave_flow.log").read_text(encoding="utf-8"))
        if case.name == "test_workbench_canvas":
            publication.verify_workbench_canvas_summary((output / "test_workbench_canvas.log").read_text(encoding="utf-8"))
        if case.name == "test_workbench_wave":
            publication.verify_workbench_wave_summary((output / "test_workbench_wave.log").read_text(encoding="utf-8"))
        if case.name == "launcher":
            publication.engine.require("SHARED_WORKBENCH_LAUNCH_READY" in (output / "launcher.log").read_text(encoding="utf-8"),
                                       "Launcher did not enter the Shared Workbench")
    verify_original_payload(package, manifest, report["manifest_sha256"])
    report["status"] = "passed"
    report["payload_unchanged"] = True
    report["log_sha256"] = {path.name: sha(path) for path in output.glob("*.log")}
    (output / "qualification.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    create = commands.add_parser("build")
    for name in ("engine", "engine-notices", "native-candidate", "vc-runtime", "output"):
        create.add_argument("--" + name, type=Path, required=True)
    check = commands.add_parser("qualify")
    check.add_argument("--package", type=Path, required=True)
    check.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    {"build": build, "qualify": qualify}[args.command](args)


if __name__ == "__main__":
    main()
